// Assembles the webview's files into desktop/dist (Tauri's frontendDist).
//
// * copies desktop/src (not its tests);
// * vendors the ONE shared ActivityPolicy (shared/web/activity-policy.js) and
//   the shared presentation defaults (assets/character/presentation.json) —
//   never a copy kept in desktop/;
// * verifies the sprite atlas against desktop/art/SHA256SUMS and refuses to
//   build on a mismatch;
// * wraps the JSON the page needs as ES modules, so the page needs no fetch
//   (the CSP gives it no connect-src beyond Tauri's IPC).
import { createHash } from "node:crypto";
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const DESKTOP = join(dirname(fileURLToPath(import.meta.url)), "..");
const ROOT = join(DESKTOP, "..");
const SRC = join(DESKTOP, "src");
const DIST = join(DESKTOP, "dist");

const sha256 = (path) => createHash("sha256").update(readFileSync(path)).digest("hex");

for (const line of readFileSync(join(DESKTOP, "art", "SHA256SUMS"), "utf8").trim().split("\n")) {
  const [digest, rel] = line.trim().split(/\s+/);
  const actual = sha256(join(ROOT, rel));
  if (actual !== digest) {
    console.error(`sprite asset ${rel} does not match its pin (${actual} != ${digest}); run desktop/art/generate_sprites.py`);
    process.exit(1);
  }
}

rmSync(DIST, { recursive: true, force: true });
cpSync(SRC, DIST, { recursive: true, filter: (p) => !p.includes(`${SRC}/test`) && !p.endsWith(".test.mjs") });
mkdirSync(join(DIST, "vendor"), { recursive: true });
cpSync(join(ROOT, "shared", "web", "activity-policy.js"), join(DIST, "vendor", "activity-policy.js"));
const asModule = (json) => `// Generated by desktop/scripts/build-frontend.mjs — do not edit.\nexport default ${JSON.stringify(JSON.parse(json))};\n`;
writeFileSync(join(DIST, "vendor", "presentation.js"), asModule(readFileSync(join(ROOT, "assets", "character", "presentation.json"), "utf8")));
writeFileSync(join(DIST, "sprites", "jarvis-atlas.js"), asModule(readFileSync(join(SRC, "sprites", "jarvis-atlas.json"), "utf8")));
rmSync(join(DIST, "sprites", "jarvis-atlas.json"));
console.log(`frontend assembled in ${DIST}`);
