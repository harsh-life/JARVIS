"""The Phase 0.4 human handoff (experiments/annotation/phase04_human_handoff.md)
must stay in step with the tooling: every command it gives is accepted by the
real CLI parser, every annotation field the validator requires is explained,
and it reveals no recognizer internals, answer key or results."""

from __future__ import annotations

import argparse
import re
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
HANDOFF = REPO / "experiments" / "annotation" / "phase04_human_handoff.md"
SPEC = REPO / "experiments" / "annotation" / "phase04_annotation_spec_v2.md"


def _text() -> str:
    return HANDOFF.read_text()


def _commands() -> list[list[str]]:
    out = []
    for line in _text().splitlines():
        line = line.strip()
        if not line.startswith("python -m experiments "):
            continue
        line = re.sub(r"<[^>]*>", "PLACEHOLDER", line.split("#")[0]).strip()
        out.append(line.split()[3:])
    return out


class _Parsed(Exception):
    pass


def test_every_command_in_the_handoff_is_accepted_by_the_cli(monkeypatch):
    from experiments.__main__ import main

    original = argparse.ArgumentParser.parse_args

    def parse_only(self, args=None, namespace=None):
        raise _Parsed(original(self, args, namespace))

    monkeypatch.setattr(argparse.ArgumentParser, "parse_args", parse_only)
    commands = _commands()
    assert len(commands) >= 9
    seen = set()
    for argv in commands:
        with pytest.raises(_Parsed) as parsed:
            main(argv)
        ns = parsed.value.args[0]
        seen.add((ns.command, getattr(ns, "action", None)))
        if ns.command == "annotation":
            assert ns.set == "phase04", argv
    assert seen >= {("annotation", a) for a in ("status", "ingest", "freeze", "verify", "validate", "agreement",
                                                "adjudicate")} | {("phase04-eval", None)}
    assert ("annotation", "freeze-rules") not in seen


def test_every_required_annotation_field_is_explained():
    from experiments.annotation_tools import ACTION_FIELDS, ENTRY_FIELDS, P04_ITEM_FIELDS

    text = _text()
    for f in (ENTRY_FIELDS - {"request_id"}) | set(P04_ITEM_FIELDS):
        assert f"`{f}`" in text, f
    for f in ACTION_FIELDS:
        assert f"`actions[].{f}`" in text, f
    spec = SPEC.read_text()
    for f in (ENTRY_FIELDS - {"request_id"}) | set(P04_ITEM_FIELDS) | ACTION_FIELDS:
        assert re.search(rf"(\*\*{f}\*\*|^## \d+\. {f}\b)", spec, re.M), f     # defined in the spec too


def test_the_handoff_states_the_counts_the_evidence_format_and_the_categories():
    from experiments.annotation_tools import CATEGORIES

    text = _text()
    assert "exactly 140 requests: 10 in each of these 14 categories" in text
    for c in CATEGORIES:
        assert f"| {c} |" in text, c
    assert "id: E1" in text and "title:" in text and "content:" in text and "Use `content`" in text
    assert "`true` or `false`" in text and "blank (`null`)" in text.lower()


def test_the_handoff_carries_the_independence_and_ground_truth_warnings():
    text = _text()
    for phrase in ("Synthetic labels", "Labels generated by a model are not human ground truth",
                   "Assistant output is not ground truth", "`n/a` means the gate could not be measured",
                   "Never run `annotation freeze-rules`", "Do not discuss the requests"):
        assert phrase in text, phrase


def test_the_handoff_reveals_no_recognizer_internals_key_contents_or_results():
    from experiments.annotation_tools import FROZEN_CODE

    text = _text()
    for path in FROZEN_CODE:
        assert Path(path).name not in text, path
    for internal in ("rules_v3", "rules_v2", "completeness", "referents", "suspicion", "recognizers",
                     "interpretation", "intent_eval", "INTENT_PROMPT", "GENERIC_HEADS"):
        assert internal not in text, internal
    for leak in ("intent_holdout_v2", "intent_dev_p04", "intent_v1", "p3-", "p4-0", "Q001:", "phase03_key"):
        assert leak not in text, leak
    assert not re.search(r"\b[0-9a-f]{40,64}\b", text)      # no hashes or key material copied in
