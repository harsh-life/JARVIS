#!/usr/bin/env bash
# Fresh-host install and server lifecycle drill (docs/DEPLOYMENT.md).
#
#   sudo tests/deploy/host_lifecycle.sh [SOURCE_CHECKOUT]
#
# Runs ONLY on a disposable Debian/Ubuntu machine with systemd as PID 1 (a CI
# runner, a scratch VM, a systemd container). It installs packages, creates the
# `jarvis` user, /opt/jarvis, /etc/jarvis and /var/lib/jarvis, and a PostgreSQL
# role and database — never point it at a host you care about.
#
# It follows the operator documentation literally: prerequisites, clone,
# deploy/postgres.md §1, deploy/bootstrap.sh, systemctl. Then it drives the
# lifecycle a real host goes through and prints one PASS/FAIL line per check:
#
#   install     bootstrap from a clean clone; a second run changes nothing
#   startup     /health and /ready, the process user, the listening address,
#               file modes of config, credentials and state
#   shutdown    `systemctl stop` is graceful (no SIGKILL) within the unit's timeout
#   persistence a SecretStore value written before a restart resolves after it
#               (the server's own startup check refuses to start otherwise)
#   crash       kill -9 → systemd restarts it → ready again
#   fail-closed a wrong KEK stops the server from starting; the right one recovers
#   local model a local (Ollama) primary starts with an empty model key credential
#   backup      deploy/backup.sh + deploy/restore.sh into an empty store
#   kek         deploy/rotate-kek.sh: new KEK works, old one no longer opens the store
#
# No real credential is used anywhere: the KEK is generated by the bootstrap
# on this throwaway host, the "model key" is a fixed non-secret placeholder,
# and the stored "client secret" is random test data. Exit status is non-zero
# if any check failed.
set -uo pipefail

SRC="${1:-$(pwd)}"
JARVIS_HOME=/opt/jarvis
ETC=/etc/jarvis
CRED=$ETC/credentials
STATE=/var/lib/jarvis
LOG_DIR="${LIFECYCLE_LOG_DIR:-/tmp/jarvis-lifecycle}"
BASE=http://127.0.0.1:8000
FAILED=0
mkdir -p "$LOG_DIR"

pass() { printf 'PASS  %s\n' "$*"; }
fail() { printf 'FAIL  %s\n' "$*"; FAILED=1; }
info() { printf '\n==== %s\n' "$*"; }
check() { local d="$1"; shift; if "$@" >>"$LOG_DIR/checks.log" 2>&1; then pass "$d"; else fail "$d"; fi; }

as_jarvis() {
    runuser -u jarvis -- env HOME=$STATE HYPERMIND_CONFIG_PATH=$ETC/config.yaml \
        PYTHONDONTWRITEBYTECODE=1 HYPERMIND_KEK="$(cat $CRED/kek)" "$@"
}
venv_py() { (cd $JARVIS_HOME && as_jarvis $JARVIS_HOME/.venv/bin/python "$@"); }

# Edit /etc/jarvis/config.yaml with the venv's PyYAML. $1 is a Python body
# operating on `c` (the parsed document).
edit_config() {
    $JARVIS_HOME/.venv/bin/python - "$ETC/config.yaml" "$1" <<'PY'
import sys, yaml
path, body = sys.argv[1], sys.argv[2]
c = yaml.safe_load(open(path))
exec(body)
yaml.safe_dump(c, open(path, "w"), sort_keys=False)
PY
}

wait_ready() {  # $1 = seconds
    local deadline=$((SECONDS + $1))
    while [ $SECONDS -lt $deadline ]; do
        [ "$(curl -s -o /dev/null -w '%{http_code}' $BASE/api/v1/ready)" = 200 ] && return 0
        sleep 1
    done
    return 1
}
not_ready_for() {  # $1 = seconds: never ready during the whole window
    local deadline=$((SECONDS + $1))
    while [ $SECONDS -lt $deadline ]; do
        [ "$(curl -s -o /dev/null -w '%{http_code}' $BASE/api/v1/ready)" = 200 ] && return 1
        sleep 1
    done
    return 0
}
main_pid() { systemctl show -p MainPID --value jarvis; }
restarts() { systemctl show -p NRestarts --value jarvis; }
mode_of() { stat -c '%a %U:%G' "$1"; }

[ "$(id -u)" -eq 0 ] || { echo "run as root on a disposable host" >&2; exit 2; }
[ -d /run/systemd/system ] || { echo "systemd is not PID 1 here" >&2; exit 2; }

# ── install ────────────────────────────────────────────────────────────────
info "prerequisites (docs/DEPLOYMENT.md §3)"
export DEBIAN_FRONTEND=noninteractive
apt-get update -q >"$LOG_DIR/apt.log" 2>&1
apt-get install -y -q --no-install-recommends git python3 python3-venv postgresql ca-certificates curl \
    >>"$LOG_DIR/apt.log" 2>&1 && pass "prerequisite packages install" || fail "prerequisite packages install"
if ! python3 -c 'import sys; sys.exit(sys.version_info < (3, 11))'; then
    # Ubuntu 22.04: python3 is 3.10 — the documented route is python3.11.
    apt-get install -y -q --no-install-recommends python3.11 python3.11-venv >>"$LOG_DIR/apt.log" 2>&1 \
        && pass "python3.11 installed (distro python3 is older than 3.11)" || fail "python3.11 install"
fi
systemctl enable --now postgresql >>"$LOG_DIR/apt.log" 2>&1
python3 --version

info "clone (committed files only — nothing from the developer's working tree)"
rm -rf $JARVIS_HOME
git -c safe.directory='*' clone -q --no-local "$SRC" $JARVIS_HOME && pass "clean clone at $(git -C $JARVIS_HOME rev-parse --short HEAD)" \
    || { fail "clone"; exit 1; }

info "PostgreSQL role and database (deploy/postgres.md §1)"
{
    runuser -u postgres -- createuser --no-superuser --no-createdb --no-createrole jarvis
    runuser -u postgres -- createdb --owner=jarvis jarvis
    runuser -u postgres -- psql -q -d jarvis -c 'REVOKE ALL ON DATABASE jarvis FROM PUBLIC'
    runuser -u postgres -- psql -q -d jarvis -c 'ALTER SCHEMA public OWNER TO jarvis'
    runuser -u postgres -- psql -q -d jarvis -c 'REVOKE CREATE ON SCHEMA public FROM PUBLIC'
} >"$LOG_DIR/postgres.log" 2>&1 && pass "database role created with no extra privilege" || fail "database role"

info "bootstrap (first run)"
# Raw output goes to a root-only file that is never uploaded; only a redacted
# copy is kept (a CI log may be public). The check reads the RAW output.
RAW=/root/.bootstrap-1.raw
(umask 077; $JARVIS_HOME/deploy/bootstrap.sh >"$RAW" 2>&1); rc=$?
sed -E 's/^( +)[A-Za-z0-9_-]{40,}={0,2}$/\1<redacted>/' "$RAW" >"$LOG_DIR/bootstrap-1.log"
if [ $rc -eq 0 ]; then pass "bootstrap.sh completes on a fresh host"; else
    fail "bootstrap.sh completes on a fresh host"; tail -40 "$LOG_DIR/bootstrap-1.log"; exit 1; fi
tail -12 "$LOG_DIR/bootstrap-1.log"
check "the KEK is not printed when the output is not a terminal" \
    bash -c "! grep -qF -- \"\$(cat $CRED/kek)\" $RAW"
rm -f "$RAW"

info "operator configuration (test values only)"
# What docs/DEPLOYMENT.md §3 asks the operator to do, with placeholders: a
# model key file and the REPLACE values. No real credential exists here.
if [ ! -s $CRED/model_api_key ]; then
    (umask 077; printf 'ci-placeholder-not-a-key\n' > $CRED/model_api_key)
fi
edit_config 'c["security"]["oidc"]["allowed_emails"] = ["lifecycle-test@example.invalid"]'
# A persistence marker: random test data stored as the OIDC client secret. The
# server's startup check resolves `client_secret_ref` and refuses to start if
# it cannot — so every later "ready" proves the store and KEK survived.
MARKER="lifecycle-$(head -c 24 /dev/urandom | base64 | tr -d '/+=')"   # never printed
HANDLE="$(printf '%s\n' "$MARKER" | venv_py -m server.composition.oidc_client_secret store 2>>"$LOG_DIR/checks.log")"
if [[ "$HANDLE" =~ ^secretstore:[0-9a-f]{32}$ ]]; then
    pass "a SecretStore value is stored under a handle"
    edit_config "c['security']['oidc']['client_secret_ref'] = '$HANDLE'"
else
    fail "a SecretStore value is stored under a handle"
fi

info "bootstrap (second run is a no-op for keys, config and data)"
kek_before=$(sha256sum $CRED/kek | cut -d' ' -f1)
cfg_before=$(sha256sum $ETC/config.yaml | cut -d' ' -f1)
if $JARVIS_HOME/deploy/bootstrap.sh >"$LOG_DIR/bootstrap-2.log" 2>&1; then
    pass "bootstrap.sh re-runs cleanly"
else
    fail "bootstrap.sh re-runs cleanly"; tail -20 "$LOG_DIR/bootstrap-2.log"
fi
check "re-run keeps the KEK" test "$kek_before" = "$(sha256sum $CRED/kek | cut -d' ' -f1)"
check "re-run keeps config.yaml" test "$cfg_before" = "$(sha256sum $ETC/config.yaml | cut -d' ' -f1)"

# ── startup ────────────────────────────────────────────────────────────────
info "startup"
systemctl enable --now jarvis >>"$LOG_DIR/checks.log" 2>&1
if wait_ready 120; then pass "GET /api/v1/ready = 200 after start"; else
    fail "GET /api/v1/ready = 200 after start"; journalctl -u jarvis --no-pager -n 60; fi
curl -s $BASE/api/v1/ready; echo
check "GET /api/v1/health = 200" curl -fsS -o /dev/null $BASE/api/v1/health
PID=$(main_pid)
check "the server runs as the jarvis user, not root" test "$(stat -c %U /proc/$PID)" = jarvis
for child in $(pgrep -P "$PID" || true); do
    check "child $child runs as jarvis" test "$(stat -c %U /proc/$child)" = jarvis
done
check "the server listens on 127.0.0.1:8000 only" \
    bash -c "ss -Hltnp | grep 'pid=$PID,' | awk '{print \$4}' | sort -u | tr '\n' ' ' | grep -qx '127.0.0.1:8000 '"
check "/etc/jarvis is root:jarvis 0750" test "$(mode_of $ETC)" = "750 root:jarvis"
check "config.yaml is root:jarvis 0640" test "$(mode_of $ETC/config.yaml)" = "640 root:jarvis"
check "credentials/ is root 0700" test "$(mode_of $CRED)" = "700 root:root"
check "the KEK file is root 0600" test "$(mode_of $CRED/kek)" = "600 root:root"
check "/var/lib/jarvis is jarvis 0700" test "$(mode_of $STATE)" = "700 jarvis:jarvis"
check "the service cannot read the KEK file directly" bash -c "! runuser -u jarvis -- cat $CRED/kek"
check "the code is not writable by the service" bash -c "! runuser -u jarvis -- touch $JARVIS_HOME/server/.w"
check "the database role is not a superuser" \
    test "$(runuser -u postgres -- psql -tAc "select rolsuper::int+rolcreaterole::int+rolcreatedb::int from pg_roles where rolname='jarvis'")" = 0

# ── graceful shutdown ──────────────────────────────────────────────────────
info "graceful shutdown"
# An idle client connection is held open across the stop, as a connected
# device would.
exec 9<>/dev/tcp/127.0.0.1/8000 || true
t0=$SECONDS
systemctl stop jarvis
stop_s=$((SECONDS - t0))
exec 9>&- 2>/dev/null || true
timeout_s=$(systemctl show -p TimeoutStopUSec --value jarvis)
echo "stop took ${stop_s}s (unit timeout ${timeout_s})"
check "systemctl stop finished in under 25s" test "$stop_s" -lt 25
check "the stop was clean (Result=success, no SIGKILL)" test "$(systemctl show -p Result --value jarvis)" = success
check "uvicorn completed its shutdown" bash -c "journalctl -u jarvis --no-pager -n 50 | grep -q 'Finished server process'"

# ── persistence across restart ─────────────────────────────────────────────
info "restart and persistence"
systemctl start jarvis
if wait_ready 120; then pass "ready again after a restart (stored secret resolved at startup)"; else
    fail "ready again after a restart"; journalctl -u jarvis --no-pager -n 40; fi
check "the stored value resolves from the CLI after restart" \
    venv_py -m server.composition.oidc_client_secret check

# ── crash recovery ─────────────────────────────────────────────────────────
info "crash recovery (kill -9)"
before=$(restarts); old=$(main_pid)
kill -9 "$old"
sleep 2
if wait_ready 60 && [ "$(main_pid)" != "$old" ]; then
    pass "systemd restarted the server after SIGKILL and it is ready"
else
    fail "systemd restarted the server after SIGKILL"; journalctl -u jarvis --no-pager -n 30
fi
check "the restart was counted" test "$(restarts)" -gt "$before"

# ── fail-closed startup ────────────────────────────────────────────────────
info "fail-closed: a wrong KEK"
cp -p $CRED/kek "$LOG_DIR/.kek.keep"
(umask 077; $JARVIS_HOME/.venv/bin/python -c \
    'from server.secrets.kek import generate_kek_value; print(generate_kek_value())' > $CRED/kek)
systemctl restart jarvis
check "with a wrong KEK the server never becomes ready (20s)" not_ready_for 20
check "the journal names the failure without printing a key" \
    bash -c "journalctl -u jarvis --no-pager -n 200 | grep -Eqi 'SecretIntegrity|integrity|KEK|unlock'"
cp -p "$LOG_DIR/.kek.keep" $CRED/kek && rm -f "$LOG_DIR/.kek.keep"
systemctl reset-failed jarvis 2>/dev/null || true
systemctl restart jarvis
check "the right KEK recovers it" wait_ready 90

# ── a local model needs no key credential ──────────────────────────────────
info "local primary model with an empty model key credential"
# docs/DEPLOYMENT.md: a local (Ollama) primary leaves model_api_key empty.
systemctl stop jarvis
: > $CRED/model_api_key
edit_config 'c["agent"]["provider"] = "ollama"; c["agent"]["model"] = "qwen2.5:1.5b"; c["agent"].pop("endpoint", None); c["agent"].pop("secret_ref", None); c["agent"].pop("pricing", None)'
systemctl reset-failed jarvis 2>/dev/null || true
systemctl start jarvis
if wait_ready 90; then pass "a local primary starts with an empty model_api_key"; else
    fail "a local primary starts with an empty model_api_key"
    systemctl status jarvis --no-pager -l | tail -15
fi

# ── backup and restore ─────────────────────────────────────────────────────
if [ -x $JARVIS_HOME/deploy/backup.sh ] && [ -x $JARVIS_HOME/deploy/restore.sh ]; then
    info "backup and restore drill"
    BK=/var/backups/jarvis-drill
    rm -rf $BK
    if $JARVIS_HOME/deploy/backup.sh --out $BK >"$LOG_DIR/backup.log" 2>&1; then
        pass "backup.sh writes a backup while the server runs"
    else
        fail "backup.sh"; tail -20 "$LOG_DIR/backup.log"
    fi
    ARCHIVE=$(ls -1 $BK/jarvis-*.tar 2>/dev/null | tail -1)
    check "the backup is root-only (0600)" test "$(stat -c %a "$ARCHIVE")" = 600
    check "the server is running again after the backup" wait_ready 60
    # Unpack every layer so the leak checks see plaintext, not gzip bytes.
    X=$(mktemp -d)
    tar -C "$X" -xf "$ARCHIVE" && gzip -d "$X"/database.*.gz && mkdir "$X/state" && tar -C "$X/state" -xzf "$X/state.tar.gz"
    check "the backup has a manifest, the store, state and config" \
        test -s "$X/MANIFEST" -a -s "$X/config.yaml" -a -d "$X/state/vault/.git"
    check "the backup does not contain the KEK" bash -c "! grep -raqF -- \"\$(cat $CRED/kek)\" '$X'"
    check "the backup does not contain the model key credential" \
        bash -c "! grep -raqF -- 'ci-placeholder-not-a-key' '$X'"
    check "the stored secret is only ciphertext in the backup" bash -c "! grep -raqF -- '$MARKER' '$X'"
    check "the backup holds the secret's handle (the store really is in it)" grep -raqF -- "${HANDLE#secretstore:}" "$X"
    rm -rf "$X"
    systemctl stop jarvis
    runuser -u postgres -- dropdb jarvis
    runuser -u postgres -- createdb --owner=jarvis jarvis
    runuser -u postgres -- psql -q -d jarvis -c 'REVOKE ALL ON DATABASE jarvis FROM PUBLIC'
    runuser -u postgres -- psql -q -d jarvis -c 'ALTER SCHEMA public OWNER TO jarvis'
    runuser -u postgres -- psql -q -d jarvis -c 'REVOKE CREATE ON SCHEMA public FROM PUBLIC'
    rm -rf ${STATE:?}/vault ${STATE:?}/vault_index ${STATE:?}/mem0_storage
    systemctl start jarvis
    check "with the store emptied the server never becomes ready (15s)" not_ready_for 15
    systemctl stop jarvis; systemctl reset-failed jarvis 2>/dev/null || true
    if $JARVIS_HOME/deploy/restore.sh "$ARCHIVE" >"$LOG_DIR/restore.log" 2>&1; then
        pass "restore.sh restores into an empty store"
    else
        fail "restore.sh"; tail -20 "$LOG_DIR/restore.log"
    fi
    systemctl start jarvis
    check "after restore the server is ready and the stored secret resolves" wait_ready 90
    check "the vault repository came back" test -d $STATE/vault/.git
fi

# ── KEK rotation ───────────────────────────────────────────────────────────
if [ -x $JARVIS_HOME/deploy/rotate-kek.sh ]; then
    info "KEK rotation"
    cp -p $CRED/kek "$LOG_DIR/.kek.old"
    if $JARVIS_HOME/deploy/rotate-kek.sh >"$LOG_DIR/rotate-kek.log" 2>&1; then
        pass "rotate-kek.sh completes"
    else
        fail "rotate-kek.sh"; tail -20 "$LOG_DIR/rotate-kek.log"
    fi
    check "the KEK file changed" bash -c "! cmp -s $CRED/kek '$LOG_DIR/.kek.old'"
    check "no kek.new is left behind" test ! -e $CRED/kek.new
    check "the new KEK is root 0600" test "$(mode_of $CRED/kek)" = "600 root:root"
    check "ready under the new KEK (stored secret still resolves)" wait_ready 60
    check "the rotation output does not print a key" bash -c \
        "! grep -qF -- \"\$(cat $CRED/kek)\" '$LOG_DIR/rotate-kek.log' && ! grep -qF -- \"\$(cat '$LOG_DIR/.kek.old')\" '$LOG_DIR/rotate-kek.log'"
    check "the rotation is in the audit trail" test "$(runuser -u jarvis -- psql -h /run/postgresql -d jarvis -tAc \
        "select count(*) from audit_events where action = 'secret.kek.rotate'")" = 1
    # The old KEK must no longer open the store: put it back and the server
    # refuses to start.
    cp -p $CRED/kek "$LOG_DIR/.kek.new"
    cp -p "$LOG_DIR/.kek.old" $CRED/kek
    systemctl restart jarvis
    check "the old KEK no longer opens the store (never ready, 20s)" not_ready_for 20
    cp -p "$LOG_DIR/.kek.new" $CRED/kek
    rm -f "$LOG_DIR/.kek.old" "$LOG_DIR/.kek.new"
    systemctl reset-failed jarvis 2>/dev/null || true
    systemctl restart jarvis
    check "the new KEK recovers it" wait_ready 60
fi

# ── diagnostics ────────────────────────────────────────────────────────────
journalctl -u jarvis --no-pager >"$LOG_DIR/journal-jarvis.log" 2>&1 || true
systemctl status jarvis --no-pager >"$LOG_DIR/status.log" 2>&1 || true
info "result: $([ $FAILED -eq 0 ] && echo ALL PASSED || echo FAILURES — see above)"
exit $FAILED
